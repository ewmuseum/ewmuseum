def indent_of(raw, obj):
    """The file's own indent, proved by reproducing its bytes; None when no indent does (the file is then never rewritten)."""
    cand = []
    for line in raw.split("\n", 40)[1:]:
        if line.startswith(" "): cand = [len(line) - len(line.lstrip(" "))]; break
    for i in cand + [x for x in (1, 2, 4) if x not in cand]:
        if json.dumps(obj, ensure_ascii=False, indent=i) + ("\n" if raw.endswith("\n") else "") == raw: return i
    return None
class J:
    """One JSON file: its bytes, its object, its indent; dump() renders the edited object in the file's own indent."""
    def __init__(self, path):
        self.path = path; self.raw = read(path); self.obj = json.loads(self.raw)
        self.ind = 1 if self.raw.strip() == "[]" else indent_of(self.raw, self.obj)
    def dump(self):
        if self.ind is None: return None
        return json.dumps(self.obj, ensure_ascii=False, indent=self.ind) + "\n"
