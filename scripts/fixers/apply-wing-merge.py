#!/usr/bin/env python3
"""apply-wing-merge (hook c104, 2026-10-06; the Janitor's D413, GAVELS 2026-10-06 "THE TITLE TEST REFINED"): one wing merges
INTO another. The first standing applier for a wing merge; the only earlier one (cwf-coastal-1997 -> scw-entity-a, 2026-09-07)
was a one-off coordinator script on the live tree.
Usage: apply-wing-merge.py <wave-dir> [--dry | --check]
Reads <wave>/delta/data/wing-merge.json:
  {"from": <wing id that goes>, "into": <wing id that stays>, "from_name": <the going wing's served name, for its stub page>,
   "alias_note": <the aliases.json note>, "stub_lede": <one or two plain sentences for the stub page>,
   "move": {"characters": [...], "units": [...], "shows": [...], "titles": [...], "reigns": [...], "rps": [...], "awards": [...]},
   "affiliations_remove": [{"a": <id>, "b": <id>, "nature": <nature>}],
   "documents": ["/promotions/<from>/archive/<file>.html", ...]}
What it does, in this order, all planned in memory first (any problem REFUSES the wave, nothing written):
  1. every named shard record moves from data/shards/<from>/ to data/shards/<into>/ with its id UNCHANGED (shows, titles, rps
     and awards get promotion=<into>; characters and units must already name <into> first, by the wave's own tenure
     corrections, which window A3 lands before this step; reigns follow their title). Moved ids are never retired:
     fix-lost-records never restores an id live in another shard of its kind.
  2. documents.json: each named page's row gets wing=<into>. The page itself stays where it is (its URL never breaks).
  3. affiliations.json: each named edge, keyed by (a, b, nature), is deleted.
  4. promotion-dates.json: <from>'s row goes; <into> is stamped updated today.
  5. aliases.json: {from: <from>, to: <into>, note} (the 2026-09-07 precedent's shape); fix-lost-records reads every alias
     `from` as retired too. No retired-ids.tsv row is written: fix-lost-records restores shard RECORDS only, never a
     promotions row, so the wing id needs none, and no record is retired.
  6. promotions.json: <from>'s row is removed.
  7. promotions/<from>/index.html and holdings.html become stub pages that link to <into> and list the named documents,
     so every old URL under /promotions/<from>/ still resolves. No served page is ever deleted.
  8. data/shards/<from>/ is removed once all seven files are empty arrays (a shard directory with no wing row is invalid).
Refuses (exit 2, nothing written) when: the file is malformed; a named id is missing, or sits in a shard other than <from>
or <into>, or in both with different content (a contradictory half-move); <from>'s shard holds a record the file does not
name; a named document row is missing or belongs to a third wing; a documents row of <from> is not named; a named
character/unit does not yet name <into> first; or, after the plan, any source registry file still carries the string <from>
as a value (a tenure, a promotion field, an edge, a provenance relation). A re-run after a full landing is a no-op (exit 0).
--check (land-check's L-WINGMERGE): only the "every named id exists" half: wings, records, edges, documents, completeness of
the <from> shard and its documents rows. Prints "WING-MERGE: n problem(s)" and each problem; exit 1 on any. Writes nothing.
--dry: the full plan, printed; writes nothing.
Every file is written in its own indent (a file whose bytes its own indent cannot reproduce is refused, never reflowed),
through a temporary name and an atomic rename, after a whitespace check (no trailing blank, no blank line at EOF)."""
